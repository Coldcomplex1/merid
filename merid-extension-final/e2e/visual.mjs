// The picture on the learning card, against a real Chromium with the unpacked
// extension loaded.
//
// The load-bearing case is the second page. A content script's tooltip lives in
// the host page's DOM, so an <img> inside it answers to the SITE's img-src, not
// to ours - which is why hotlinking to an image host would come up blank on
// every strict site on the web. Bundling and addressing the file through
// chrome.runtime.getURL is supposed to sidestep that entirely, because the
// chrome-extension: scheme is exempt from the page's policy.
//
// "Supposed to" is the reason this file exists. If the CSP case goes red the
// design is wrong, not the test.
//
// Fixtures: if vis/ is empty this script draws its own placeholder pictures
// first, with a throwaway Chromium, and deletes them on the way out. Real
// artwork is generated by the dataset pipeline and committed; placeholders are
// not, because a checked-in gradient claiming to illustrate "abolish" is worse
// than no picture at all. Either way the test runs.
import { chromium } from 'playwright';
import http from 'node:http';
import path from 'node:path';
import fs from 'node:fs';
import { createRequire } from 'node:module';

const EXT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const require = createRequire(import.meta.url);
const C = require(path.join(EXT, 'lib/vocab-core.js'));
const Visual = require(path.join(EXT, 'lib/visual.js'));

const VIS_DIR = path.join(EXT, 'vis');
const INDEX_FILE = path.join(EXT, 'visual-index.json');

// The headwords the fixture page below is written to surface, and what each is
// there to prove. The test guarantees the first group has a picture and the
// second a concept bucket.
//
// The second group is not decoration. visualFor draws only what the index
// actually names and returns null for everything else, so a word with neither
// a photograph nor a bucket now gets no picture box at all - which is the whole
// point of the rule, and also means a fixture that only guarantees photographs
// cannot test the glyph path. Which of these the scanner picks for a given run
// is its own business; between them the page cannot surface a word the index
// has never heard of.
const NEEDS_PHOTO = ['abolish', 'absence'];
const NEEDS_GLYPH = ['abuse', 'absurd', 'abundant', 'academy', 'accelerate',
    'accessible', 'acceptance', 'achievement'];

/** A concept bucket per glyph fixture word. Any drawable name will do here. */
const GLYPH_BUCKET = 'knowledge';

/** The slug for a C1 headword, computed the way the browser computes it. */
function slugForWord(word) {
    const rows = C.parseCSV(fs.readFileSync(path.join(EXT, 'dataset-C1.csv'), 'utf8'))
        .filter(C.validateEntry);
    const row = rows.find(r => r.word === word);
    return row ? Visual.slugFor(C.normalizeEntry(row, 'c1')) : null;
}

/**
 * Make sure the words this page shows actually have pictures, and say what to
 * undo afterwards.
 *
 * Not "generate pictures if vis/ is empty". Once the dataset pipeline has run,
 * vis/ is full - of pictures for whichever words turned out to be
 * photographable, which is a set that changes every time the pipeline runs and
 * has no reason to include the two words this fixture happens to surface. A
 * test that depended on that overlap would pass today and fail after an
 * unrelated re-run.
 *
 * So it works the other way round: name the words the page needs, and fill in
 * only what is missing. Real artwork is never touched, and the placeholders are
 * removed on the way out - a checked-in gradient claiming to illustrate
 * "abolish" would be worse than no picture at all.
 *
 * The encoder is the browser: canvas plus toDataURL('image/webp') gives real
 * WebP bytes, and nothing in this repo encodes images.
 */
async function makeFixtures() {
    // One read, used twice. This asked existsSync and then read, twice over the
    // same file - so the index could be written between the question and the
    // answer, and again between the two reads, leaving `originalIndex` holding
    // something the cleanup would later restore over the top of a newer file.
    let originalIndex = null;
    try { originalIndex = fs.readFileSync(INDEX_FILE, 'utf8'); } catch (e) { /* none yet */ }
    const index = originalIndex !== null
        ? JSON.parse(originalIndex)
        : { v: 1, fmt: 'webp', dim: [320, 160], photo: [], icon: {} };

    // The buckets first: they cost nothing to add, need no browser, and are
    // what stops a word on this page drawing no box at all.
    index.icon = index.icon || {};
    const named = new Set(Object.values(index.icon).flatMap(v => String(v).split(/\s+/)));
    const addBuckets = NEEDS_GLYPH.map(slugForWord)
        .filter(sl => sl && !named.has(sl) && !(index.photo || []).includes(sl));
    let wroteIndex = false;
    if (addBuckets.length) {
        index.icon[GLYPH_BUCKET] = [index.icon[GLYPH_BUCKET], ...addBuckets]
            .filter(Boolean).join(' ');
        wroteIndex = true;
    }

    const have = new Set(index.photo || []);
    const wanted = NEEDS_PHOTO.map(slugForWord).filter(Boolean);
    // Named by the index but absent from disk counts as missing too - the two
    // can disagree. Opened rather than asked about: the answer to "can I read
    // this" is the same syscall as the reason for asking.
    const onDisk = f => {
        try { fs.readFileSync(f); return true; } catch (e) { return false; }
    };
    const missing = wanted.filter(slug =>
        !have.has(slug) || !onDisk(path.join(VIS_DIR, slug + '.' + (index.fmt || 'webp'))));
    if (!missing.length) {
        // Nothing to encode, but the buckets above may still be new. Report the
        // original index so the cleanup puts the reader's own file back.
        if (wroteIndex) {
            fs.writeFileSync(INDEX_FILE, JSON.stringify(index, null, 2) + '\n');
            return { made: [], originalIndex, madeDir: false };
        }
        return { made: [], originalIndex: null, madeDir: false };
    }

    // mkdirSync with recursive returns the first directory it created, or
    // undefined when there was nothing to create. One call, one answer - no
    // window between asking and acting.
    const madeDir = fs.mkdirSync(VIS_DIR, { recursive: true }) !== undefined;
    const fmt = index.fmt || 'webp';

    const browser = await chromium.launch({
        executablePath: process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium'
    });
    const page = await browser.newPage();
    const made = [];
    for (const [i, slug] of missing.entries()) {
        const dataUrl = await page.evaluate(({ hue, mime }) => {
            const c = document.createElement('canvas');
            c.width = 320; c.height = 160;
            const g = c.getContext('2d');
            const grad = g.createLinearGradient(0, 0, 320, 160);
            grad.addColorStop(0, `hsl(${hue} 70% 45%)`);
            grad.addColorStop(1, `hsl(${hue + 40} 65% 62%)`);
            g.fillStyle = grad; g.fillRect(0, 0, 320, 160);
            g.fillStyle = 'rgba(255,255,255,.85)';
            for (let x = 10; x < 320; x += 26) for (let y = 10; y < 160; y += 26) g.fillRect(x, y, 6, 6);
            return c.toDataURL(mime, 0.5);
        }, { hue: (i * 97) % 360, mime: fmt === 'avif' ? 'image/webp' : 'image/' + fmt });
        const file = path.join(VIS_DIR, slug + '.' + fmt);
        // 'wx' rather than a plain write, and the file is recorded as ours only
        // if this call created it. That is what actually keeps the promise in
        // the comment above - real artwork is never touched - because a file
        // that appeared between the check above and this line would otherwise
        // be overwritten here and deleted by the cleanup on the way out.
        try {
            fs.writeFileSync(file, Buffer.from(dataUrl.split(',')[1], 'base64'), { flag: 'wx' });
            made.push(file);
        } catch (e) {
            if (e.code !== 'EEXIST') throw e;
        }
        if (!have.has(slug)) index.photo.push(slug);
    }
    await browser.close();
    fs.writeFileSync(INDEX_FILE, JSON.stringify(index, null, 2) + '\n');
    return { made, originalIndex, madeDir };
}

const fixtures = await makeFixtures();
function cleanUpFixtures() {
    for (const f of fixtures.made) { try { fs.unlinkSync(f); } catch (e) { /* gone */ } }
    if (fixtures.originalIndex !== null) {
        try { fs.writeFileSync(INDEX_FILE, fixtures.originalIndex); } catch (e) { /* gone */ }
    } else if (fixtures.made.length) {
        try { fs.unlinkSync(INDEX_FILE); } catch (e) { /* gone */ }
    }
    if (fixtures.madeDir) { try { fs.rmdirSync(VIS_DIR); } catch (e) { /* not empty */ } }
}
process.on('exit', cleanUpFixtures);

// Read after makeFixtures, so this is the index the browser will actually load.
const SHIPPED_INDEX = (() => {
    try { return JSON.parse(fs.readFileSync(INDEX_FILE, 'utf8')); }
    catch (e) { return { photo: [], icon: {} }; }
})();
const PHOTO_SLUGS = new Set(SHIPPED_INDEX.photo || []);
/** Every slug the index names at all - a picture or a concept, either way. */
const NAMED_SLUGS = new Set([
    ...PHOTO_SLUGS,
    ...Object.values(SHIPPED_INDEX.icon || {}).flatMap(v => String(v).split(/\s+/))
].filter(Boolean));

/** Does this headword have a bundled picture, according to the shipped index? */
function hasPhoto(word) {
    const slug = slugForWord(word);
    return !!slug && PHOTO_SLUGS.has(slug);
}

/**
 * Does the index know this headword at all?
 *
 * The card draws a picture box if and only if this is true - see the note at
 * the top of lib/visual.js. A word the index has never heard of gets no box,
 * which is deliberate and is what section 4 checks against.
 */
function indexKnows(word) {
    const slug = slugForWord(word);
    return !!slug && NAMED_SLUGS.has(slug);
}

// Vietnamese meanings lifted from dataset-C1.csv so the matching is real.
// "bãi bỏ" -> abolish and "sự vắng mặt" -> absence are the two with a bundled
// picture; the rest are there to be drawn as concept glyphs.
