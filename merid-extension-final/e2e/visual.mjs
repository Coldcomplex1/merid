function page(extraHead = '') {
    return `<!doctype html><html lang="vi"><head><meta charset="utf-8">
<title>Thử nghiệm</title>${extraHead}</head><body>${BODY}</body></html>`;
}

// Three fixtures, three different things that could break the picture.
const ROUTES = {
    // 1. An ordinary page. Baseline.
    '/plain': { head: '', headers: {} },
    // 2. A site that forbids third-party images. This is the one that matters.
    '/strict': { head: '', headers: { 'Content-Security-Policy': "img-src 'self'; default-src 'self' 'unsafe-inline'" } },
    // 3. A site whose reset fights us for the <img> box. `height: auto
    //    !important` beats a class selector, and would resize the card after it
    //    had already been positioned - so the strip is sized by its container,
    //    not by the image.
    '/hostile-css': { head: '<style>img{height:auto!important;max-width:100%!important;width:auto!important}</style>', headers: {} }
};

const server = http.createServer((req, res) => {
    const route = ROUTES[new URL(req.url, 'http://x').pathname] || ROUTES['/plain'];
    res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8', ...route.headers });
    res.end(page(route.head));
});
await new Promise(r => server.listen(0, r));
const base = `http://127.0.0.1:${server.address().port}`;

const ctx = await chromium.launchPersistentContext(
    path.join(process.env.TMPDIR || '/tmp', 'merid-visual-' + Date.now()),
    {
        headless: true,
        executablePath: process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium',
        args: [`--disable-extensions-except=${EXT}`, `--load-extension=${EXT}`]
    }
);

// The worker starts on its own, but not always before the first page does.
if (!ctx.serviceWorkers().length) await ctx.waitForEvent('serviceworker', { timeout: 20000 });

const fail = [];
const ok = [];
const check = (cond, label, extra = '') => (cond ? ok : fail).push(label + (extra ? ` -> ${extra}` : ''));

async function openHighlighted(url) {
    const p = await ctx.newPage();
    await p.goto(url, { waitUntil: 'domcontentloaded' });
    await p.waitForSelector('.vocab-master-highlight', { timeout: 20000 }).catch(() => { });
    return p;
}

/**
 * Open the card for `word`.
 *
 * A real pointer move is the wrong tool here: an already-open card sits over
 * the page and swallows the hover meant for the next span, so playwright waits
 * out its whole retry budget on an element that is genuinely covered. The
 * extension listens for `mouseover` on document, so dispatching one says the
 * same thing without fighting the layout - which is how e2e/interaction.mjs
 * drives it too.
 */
async function hover(p, word) {
    const found = await p.evaluate((w) => {
        const el = document.querySelector(`.vocab-master-highlight[data-word="${w}"]`);
        if (!el) return false;
        el.dispatchEvent(new MouseEvent('mouseover', { bubbles: true }));
        return true;
    }, word);
    if (!found) return null;
    await p.waitForSelector('.vocab-master-tooltip .vm-card', { timeout: 5000 }).catch(() => { });
    return true;
}

/** Wait for whatever picture is on the open card to finish loading (or fail). */
async function settled(p) {
    await p.waitForFunction(() => {
        const i = document.querySelector('.vm-visual-img');
        return !i || i.complete;
    }, { timeout: 5000 }).catch(() => { });
}

// ---------------------------------------------------------------------------
// 1. Baseline: a bundled picture decodes on an ordinary page.
// ---------------------------------------------------------------------------
{
    const p = await openHighlighted(base + '/plain');
    const words = await p.$$eval('.vocab-master-highlight', els => els.map(e => e.dataset.word));
    check(words.length > 0, 'page has highlighted words', words.join(','));

    const withPhoto = words.find(hasPhoto);
    if (withPhoto) {
        await hover(p, withPhoto);
        const img = await p.$('.vocab-master-tooltip .vm-visual-img');
        check(!!img, `card for "${withPhoto}" has a picture element`);
        if (img) {
            const src = await img.getAttribute('src');
            check(/^chrome-extension:\/\//.test(src || ''), 'picture is addressed through the extension', src);
            // The assertion that actually means something. A correct src with a
            // broken file still passes "the element exists".
            await settled(p);
            const w = await img.evaluate(i => i.naturalWidth);
            check(w > 0, 'picture actually decoded on a plain page', `naturalWidth=${w}`);
            const ready = await img.evaluate(i => i.classList.contains('vm-ready'));
            check(ready, 'picture faded in (load handler ran)');
        }
    } else {
        check(false, 'a word with a bundled picture appeared on the page', words.join(','));
    }
    await p.close();
}

// ---------------------------------------------------------------------------
// 2. THE ONE THAT MATTERS: a site that allows same-origin images only.
// ---------------------------------------------------------------------------
{
    const p = await openHighlighted(base + '/strict');
    const words = await p.$$eval('.vocab-master-highlight', els => els.map(e => e.dataset.word));
    const withPhoto = words.find(hasPhoto);
    if (withPhoto) {
        await hover(p, withPhoto);
        const img = await p.$('.vocab-master-tooltip .vm-visual-img');
        check(!!img, 'card still has a picture element under img-src \'self\'');
        if (img) {
            await settled(p);
            const w = await img.evaluate(i => i.naturalWidth);
            check(w > 0, "picture decoded despite the page's img-src 'self'", `naturalWidth=${w}`);
        }
    } else {
        check(false, 'a word with a bundled picture appeared on the strict page', words.join(','));
    }
    await p.close();
}

// ---------------------------------------------------------------------------
// 3. A hostile image reset must not move a card that is already placed.
// ---------------------------------------------------------------------------
{
    const p = await openHighlighted(base + '/hostile-css');
    const words = await p.$$eval('.vocab-master-highlight', els => els.map(e => e.dataset.word));
    const withPhoto = words.find(hasPhoto);
    if (withPhoto) {
        // Measure the moment the card appears, then again once the picture is in.
        await hover(p, withPhoto);
        const before = await p.$eval('.vocab-master-tooltip', el => el.getBoundingClientRect().height);
        await settled(p);
        const after = await p.$eval('.vocab-master-tooltip', el => el.getBoundingClientRect().height);
        check(Math.abs(after - before) < 1,
            'card height is settled before the picture arrives', `${before} -> ${after}`);
        const w = await p.$eval('.vm-visual-img', i => i.naturalWidth).catch(() => 0);
        check(w > 0, 'picture decoded despite the page fighting for the <img> box');
    } else {
        check(false, 'a word with a bundled picture appeared on the hostile-css page', words.join(','));
    }
    await p.close();
}

// ---------------------------------------------------------------------------
// 4. An abstract word gets a glyph - and a word the index does not know gets
//    no box at all, rather than its own first letter.
//
//    That second half is the rule 1.7.1 was withdrawn for the want of. With no
//    artwork generated, every entry fell through to a coloured box with a
//    letter in it; the card now simply has no picture panel. The check below is
//    written as an equivalence rather than two hard-coded word lists, so it
//    holds whichever words the scanner happens to surface on a given run.
// ---------------------------------------------------------------------------
{
    const p = await openHighlighted(base + '/plain');
    const words = await p.$$eval('.vocab-master-highlight', els => els.map(e => e.dataset.word));
    // Which words have a picture is a property of vis/, not something to
    // hard-code here: ask each card what it actually drew.
    let sawGlyph = null;
    for (const word of words) {
        await hover(p, word);
        const kind = await p.$eval('.vocab-master-tooltip .vm-visual',
            el => el.className).catch(() => null);
        const known = indexKnows(word);
        check(!!kind === known,
            known
                ? `card for "${word}" has an artwork box`
                : `card for "${word}" has no artwork box, because the index does not name it`,
            String(kind));
        if (kind && /vm-visual--(icon|generic)/.test(kind)) { sawGlyph = word; break; }
    }
    check(!!sawGlyph, 'at least one word drew a glyph rather than a photo', words.join(','));
    if (sawGlyph) {
        const box = await p.$('.vocab-master-tooltip .vm-visual');
        const hue = await box.evaluate(el => el.style.getPropertyValue('--vm-vis-hue'));
        const angle = await box.evaluate(el => el.style.getPropertyValue('--vm-vis-angle'));
        const pat = await box.evaluate(el => el.dataset.vmPat);
        check(hue !== '' && angle !== '' && pat !== undefined,
            'glyph box carries all three generated axes', `hue=${hue} angle=${angle} pat=${pat}`);
        const drawn = await box.evaluate(el => !!el.querySelector('svg, .vm-visual-letter'));
        check(drawn, 'glyph box is not empty');
        const noImg = await box.evaluate(el => !el.querySelector('img'));
        check(noImg, 'glyph box asks for no image at all');
    }
    await p.close();
}

// ---------------------------------------------------------------------------
// 5. Card stays on screen on a short window, at the bottom of the page.
// ---------------------------------------------------------------------------
{
    const p = await ctx.newPage();
    await p.setViewportSize({ width: 900, height: 560 });
    await p.goto(base + '/plain', { waitUntil: 'domcontentloaded' });
    await p.waitForSelector('.vocab-master-highlight', { timeout: 20000 }).catch(() => { });
    const spans = await p.$$('.vocab-master-highlight');
    if (spans.length) {
        await spans[spans.length - 1].scrollIntoViewIfNeeded();
        await p.evaluate(() => {
            const els = document.querySelectorAll('.vocab-master-highlight');
            els[els.length - 1].dispatchEvent(new MouseEvent('mouseover', { bubbles: true }));
        });
        await p.waitForSelector('.vocab-master-tooltip .vm-card', { timeout: 5000 }).catch(() => { });
        const box = await p.$eval('.vocab-master-tooltip', el => {
            const r = el.getBoundingClientRect();
            return { top: r.top, bottom: r.bottom, vh: window.innerHeight };
        });
        check(box.top >= -1, 'card does not run off the top', JSON.stringify(box));
        check(box.bottom <= box.vh + 1, 'card does not run off the bottom', JSON.stringify(box));
    } else {
        check(false, 'short viewport page had highlighted words');
    }
    await p.close();
}

// ---------------------------------------------------------------------------
// 6. Turning the setting off removes the picture and leaves the page alone.
// ---------------------------------------------------------------------------
{
    const p = await openHighlighted(base + '/plain');
    const before = await p.$$eval('.vocab-master-highlight', els => els.map(e => e.textContent));
    // page.evaluate runs in the page's world, which has no `chrome` - the
    // content script lives in an isolated one. The worker does have it, and
    // writing there is also the honest path: it is where the Settings page
    // writes too, so the content script hears about it the same way.
    const [worker] = ctx.serviceWorkers();
    await worker.evaluate(() => new Promise(r => chrome.storage.sync.set({ visualsEnabled: false }, r)));
    await p.waitForTimeout(400);
    const after = await p.$$eval('.vocab-master-highlight', els => els.map(e => e.textContent));
    check(JSON.stringify(before) === JSON.stringify(after),
        'turning pictures off does not rewrite the page');

    const words = await p.$$eval('.vocab-master-highlight', els => els.map(e => e.dataset.word));
    if (words.length) {
        await hover(p, words[0]);
        const box = await p.$('.vocab-master-tooltip .vm-visual');
        check(!box, 'no artwork box once the setting is off');
        const card = await p.$('.vocab-master-tooltip .vm-card');
        check(!!card, 'the rest of the card is untouched');
    }
    await p.close();
}

